//go:build windows

package input

// HID usage codes (usage page 0x07) to PS/2 set 1 scan codes, which is what
// SendInput's KEYEVENTF_SCANCODE wants.
//
// Scan codes rather than virtual keys, for the reason inject_windows.go gives:
// a virtual key is already through the layout, and §13's contract is that the
// target applies its own. The bool is Windows' extended-key flag, which is what
// distinguishes the arrow keys and the keypad's enter from their non-extended
// twins.
var hidToScan = map[uint16]struct {
	code     uint16
	extended bool
}{
	0x04: {0x1e, false}, 0x05: {0x30, false}, 0x06: {0x2e, false}, // a b c
	0x07: {0x20, false}, 0x08: {0x12, false}, 0x09: {0x21, false}, // d e f
	0x0a: {0x22, false}, 0x0b: {0x23, false}, 0x0c: {0x17, false}, // g h i
	0x0d: {0x24, false}, 0x0e: {0x25, false}, 0x0f: {0x26, false}, // j k l
	0x10: {0x32, false}, 0x11: {0x31, false}, 0x12: {0x18, false}, // m n o
	0x13: {0x19, false}, 0x14: {0x10, false}, 0x15: {0x13, false}, // p q r
	0x16: {0x1f, false}, 0x17: {0x14, false}, 0x18: {0x16, false}, // s t u
	0x19: {0x2f, false}, 0x1a: {0x11, false}, 0x1b: {0x2d, false}, // v w x
	0x1c: {0x15, false}, 0x1d: {0x2c, false}, // y z

	0x1e: {0x02, false}, 0x1f: {0x03, false}, 0x20: {0x04, false}, // 1 2 3
	0x21: {0x05, false}, 0x22: {0x06, false}, 0x23: {0x07, false}, // 4 5 6
	0x24: {0x08, false}, 0x25: {0x09, false}, 0x26: {0x0a, false}, // 7 8 9
	0x27: {0x0b, false}, // 0

	0x28: {0x1c, false}, // enter
	0x29: {0x01, false}, // escape
	0x2a: {0x0e, false}, // backspace
	0x2b: {0x0f, false}, // tab
	0x2c: {0x39, false}, // space
	0x2d: {0x0c, false}, // minus
	0x2e: {0x0d, false}, // equal
	0x2f: {0x1a, false}, // left brace
	0x30: {0x1b, false}, // right brace
	0x31: {0x2b, false}, // backslash
	0x32: {0x2b, false}, // non-US hash
	0x33: {0x27, false}, // semicolon
	0x34: {0x28, false}, // apostrophe
	0x35: {0x29, false}, // grave
	0x36: {0x33, false}, // comma
	0x37: {0x34, false}, // dot
	0x38: {0x35, false}, // slash
	0x39: {0x3a, false}, // caps lock

	0x3a: {0x3b, false}, 0x3b: {0x3c, false}, 0x3c: {0x3d, false}, // F1-F3
	0x3d: {0x3e, false}, 0x3e: {0x3f, false}, 0x3f: {0x40, false}, // F4-F6
	0x40: {0x41, false}, 0x41: {0x42, false}, 0x42: {0x43, false}, // F7-F9
	0x43: {0x44, false}, 0x44: {0x57, false}, 0x45: {0x58, false}, // F10-F12

	0x46: {0x37, true},  // print screen
	0x47: {0x46, false}, // scroll lock
	0x48: {0x45, false}, // pause
	0x49: {0x52, true},  // insert
	0x4a: {0x47, true},  // home
	0x4b: {0x49, true},  // page up
	0x4c: {0x53, true},  // delete
	0x4d: {0x4f, true},  // end
	0x4e: {0x51, true},  // page down
	0x4f: {0x4d, true},  // right
	0x50: {0x4b, true},  // left
	0x51: {0x50, true},  // down
	0x52: {0x48, true},  // up

	0x53: {0x45, false}, // num lock
	0x54: {0x35, true},  // keypad slash
	0x55: {0x37, false}, // keypad asterisk
	0x56: {0x4a, false}, // keypad minus
	0x57: {0x4e, false}, // keypad plus
	0x58: {0x1c, true},  // keypad enter
	0x59: {0x4f, false}, 0x5a: {0x50, false}, 0x5b: {0x51, false}, // keypad 1-3
	0x5c: {0x4b, false}, 0x5d: {0x4c, false}, 0x5e: {0x4d, false}, // keypad 4-6
	0x5f: {0x47, false}, 0x60: {0x48, false}, 0x61: {0x49, false}, // keypad 7-9
	0x62: {0x52, false}, 0x63: {0x53, false}, // keypad 0 and dot
	0x64: {0x56, false}, // 102nd key

	0xe0: {0x1d, false}, 0xe1: {0x2a, false}, // left ctrl, left shift
	0xe2: {0x38, false}, 0xe3: {0x5b, true}, // left alt, left meta
	0xe4: {0x1d, true}, 0xe5: {0x36, false}, // right ctrl, right shift
	0xe6: {0x38, true}, 0xe7: {0x5c, true}, // right alt, right meta
}

func windowsScanCode(usage uint16) (code uint16, extended bool, ok bool) {
	entry, found := hidToScan[usage]
	return entry.code, entry.extended, found
}
